export function getUnidades(programaId: string) {
  const p = programas.find((p) => p.id === programaId);
  return p ? p.unidades : [];
}
export function getTemas(programaId: string, unidadId: string) {
  const us = getUnidades(programaId);
  const u = us.find((u) => u.id === unidadId);
  return u ? u.temas : [];
}
export function getOAs(programaId: string, unidadId: string, temaId: string) {
  const ts = getTemas(programaId, unidadId);
  const t = ts.find((t) => t.id === temaId);
  return t ? t.oas : [];
}